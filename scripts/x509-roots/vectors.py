#!/usr/bin/env python3
"""Generate crates/oskac/tests/vectors/x509_mozilla_roots.osk: every real root of the store.

    python3 -I scripts/x509-roots/vectors.py CERTDATA.txt > crates/oskac/tests/vectors/x509_mozilla_roots.osk

CERTDATA.txt is the file `generate.py` was given. The output is a test file:
for each root trusted for TLS server authentication it holds the certificate,
and the verdict on its own signature that the Python `cryptography` package
gives (`ok`, or `UnsupportedAlgorithm` for a signature or key `std.x509` does
not read, such as an SHA-1 signature). The tests check that `std.x509` parses
every one, finds it in `TrustConfig.default()`, and gives the same verdict.
"""

import importlib.util
import os
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, padding, rsa

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("generate", os.path.join(here, "generate.py"))
generate = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generate)

SUPPORTED_HASHES = (hashes.SHA256, hashes.SHA384, hashes.SHA512)


def verdict(der):
    """`ok` when std.x509 reads the self-signature, with the signature checked here too."""
    cert = x509.load_der_x509_certificate(der)
    key = cert.public_key()
    supported_key = (
        (isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name in ("secp256r1", "secp384r1"))
        or (isinstance(key, rsa.RSAPublicKey) and 2048 <= key.key_size <= 8192)
        or isinstance(key, ed25519.Ed25519PublicKey)
    )
    hash_alg = cert.signature_hash_algorithm
    supported_sig = isinstance(key, ed25519.Ed25519PublicKey) or isinstance(hash_alg, SUPPORTED_HASHES)
    if not (supported_key and supported_sig):
        return "UnsupportedAlgorithm"
    cert.verify_directly_issued_by(cert)
    return "ok"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    roots = generate.trusted_roots(generate.objects(raw.decode("utf-8")))
    out = []
    w = out.append
    w("// `std.x509` over every real root of Mozilla's store (the roots trusted for TLS server")
    w("// authentication): each parses, is in `TrustConfig.default()`, is a CA, and gives the")
    w("// verdict on its own signature that the Python `cryptography` package gave when this")
    w("// file was generated by `scripts/x509-roots/vectors.py`. These are real certificates,")
    w("// with their real encodings, algorithms and extensions, so this is the test that the")
    w("// parser reads what CAs actually issue. It runs natively (`native_x509.rs`).")
    w(f"// Source: certdata.txt, SHA-256 {__import__('hashlib').sha256(raw).hexdigest()}.")
    w("")
    w("use std.x509")
    w("")
    w("struct Vector { name: String, verdict: String, der: String }")
    w("")
    w("fn vectors() -> List<Vector> {")
    w("    [")
    for label, der, _subject, _spki, _after, _ski in roots:
        w(f'        Vector(name: {generate.osk_string(label)}, verdict: "{verdict(der)}", der: "{der.hex()}"),')
    w("    ]")
    w("}")
    w(
        '''
fn hex(text: String) -> Bytes {
    Bytes.from_hex(text).unwrap_or(Bytes.new())
}

fn kind(error: x509.X509Error) -> String {
    match error {
        x509.X509Error.UnsupportedAlgorithm => "UnsupportedAlgorithm"
        x509.X509Error.UnknownIssuer => "UnknownIssuer"
        x509.X509Error.BadSignature => "BadSignature"
        _ => "other"
    }
}

test "every root parses, is a CA and is in the Mozilla store" {
    let store = x509.TrustConfig.default()
    t.assert_eq(store.len(), vectors().len())
    for v in vectors() {
        match x509.Certificate.parse(hex(v.der)) {
            Ok(cert) => {
                t.assert_eq(cert.is_ca(), true)
                t.assert_eq(store.contains(cert), true)
                t.assert_eq(cert.to_der(), hex(v.der))
            }
            Err(_) => t.assert_eq(v.name, "a root that parses")
        }
    }
}

test "every root's own signature gives the verdict the reference library did" {
    for v in vectors() {
        match x509.Certificate.parse(hex(v.der)) {
            Ok(cert) => {
                let got = match cert.signed_by(cert) {
                    Ok(_) => "ok"
                    Err(e) => kind(e)
                }
                t.assert_eq(got, v.verdict)
            }
            Err(_) => t.assert_eq(v.name, "a root that parses")
        }
    }
}
'''
    )
    sys.stdout.write("\n".join(out))


main()
